import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { resolveAddonIdentity } from '../packages/configs/src/utils/addonIdentity.ts'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const endpoints = []

async function collect(file, module, prefix) {
  const { contract } = await import(pathToFileURL(resolve(root, file)))

  function walk(value, route = []) {
    if (value?.method) {
      endpoints.push({
        id: `${module}:${route.join('/')}`,
        module,
        route: route.join('/'),
        path: `${prefix}/${route.join('/')}`,
        method: value.method.toUpperCase(),
        encrypted: value.encrypted,
        noAuth: value.noAuth,
        description: value.description,
        input: value.input,
        output: value.output?.OK,
        media: value.media
      })
    } else if (value && typeof value === 'object') {
      for (const [key, child] of Object.entries(value))
        walk(child, [...route, key])
    }
  }
  walk(contract)
}
await collect('packages/api/src/contract.ts', 'core', '/api')

for (const name of readdirSync(resolve(root, 'modules')).sort()) {
  if (!name.startsWith('monolith--')) continue

  const file = `modules/${name}/client/contract.ts`

  try {
    readFileSync(resolve(root, file))
  } catch {
    continue
  }

  const pkg = JSON.parse(
    readFileSync(resolve(root, `modules/${name}/package.json`), 'utf8')
  )
  const { remoteId } = resolveAddonIdentity(pkg)
  await collect(
    file,
    name.replace('monolith--', ''),
    `/api/modules/${remoteId}`
  )
}

const output = resolve(root, 'apps/android/app/src/main/assets/contracts.json')
mkdirSync(dirname(output), { recursive: true })
const serialized = JSON.stringify({ version: 1, endpoints }) + '\n'

function generated(file, content) {
  let previous

  try {
    previous = readFileSync(file, 'utf8')
  } catch {
    // The first generation has no existing file to compare.
  }
  if (process.argv.includes('--check')) {
    if (previous !== content)
      throw Error(`Android generated source is stale: ${file}`)
  } else if (previous !== content) writeFileSync(file, content)
}
generated(output, serialized)
const strings = readFileSync(
  resolve(root, 'apps/android/app/src/main/res/values/strings.xml'),
  'utf8'
)
const names = [...strings.matchAll(/<string name="([a-z0-9_]+)"/g)].map(
  match => match[1]
)
generated(
  resolve(
    root,
    'apps/android/app/src/main/java/app/monolith/android/ui/StringResources.kt'
  ),
  '// Generated by tools/android-contracts.mjs from Android string resources.\n' +
    'package app.monolith.android.ui\n\nimport app.monolith.android.R\n\n' +
    'internal val stringResources = mapOf(\n' +
    names.map(name => `    "${name}" to R.string.${name},`).join('\n') +
    '\n)\n'
)
console.log(
  `Android: ${endpoints.length} contract operations across ${new Set(endpoints.map(e => e.module)).size} modules`
)
