import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync
} from 'node:fs'
import { createRequire } from 'node:module'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const requireUI = createRequire(join(root, 'packages/ui/package.json'))
const collections = JSON.parse(
  readFileSync(
    requireUI.resolve('@iconify/collections/collections.json'),
    'utf8'
  )
)
const requested = new Map()
function scan(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (
      ['node_modules', 'dist', 'target', 'generated', '__tests__'].includes(
        entry.name
      )
    )
      continue
    const path = join(directory, entry.name)
    if (entry.isDirectory()) scan(path)
    else if (/\.(tsx?|json)$/.test(path))
      for (const match of readFileSync(path, 'utf8').matchAll(
        /['"`]([a-z][a-z0-9-]*):([a-z0-9][a-z0-9-]*)['"`]/g
      )) {
        if (!collections[match[1]]) continue
        const set = requested.get(match[1]) ?? new Set()
        set.add(match[2])
        requested.set(match[1], set)
      }
  }
}
for (const path of [
  'apps/web/src',
  'packages/ui/src',
  ...readdirSync(join(root, 'modules')).map(name => `modules/${name}/client`)
])
  if (existsSync(join(root, path))) scan(join(root, path))
// Sidebar icons come from manifests as well as client source.
for (const entry of readdirSync(join(root, 'modules'), { withFileTypes: true })) {
  if (!entry.isDirectory()) continue
  const name = entry.name
  // Shared catalogs also supply icons to bundled addon dashboards.
  for (const file of readdirSync(join(root, 'modules', name))) {
    if (!file.endsWith('Shared.ts')) continue
    for (const match of readFileSync(join(root, 'modules', name, file), 'utf8').matchAll(/['"`]([a-z][a-z0-9-]*):([a-z0-9][a-z0-9-]*)['"`]/g)) {
      if (!collections[match[1]]) continue
      const names = requested.get(match[1]) ?? new Set()
      names.add(match[2])
      requested.set(match[1], names)
    }
  }
  const manifest = join(root, 'modules', name, 'package.json')
  if (!existsSync(manifest)) continue
  const icon = JSON.parse(readFileSync(manifest, 'utf8')).monolith?.icon
  if (typeof icon !== 'string') continue
  const [prefix, glyph] = icon.split(':')
  if (!collections[prefix] || !glyph) continue
  const names = requested.get(prefix) ?? new Set()
  names.add(glyph)
  requested.set(prefix, names)
}
const output = resolve(root, 'packages/ui/src/assets/icons')
mkdirSync(output, { recursive: true })
const icons = [],
  notices = []
for (const [prefix, names] of [...requested].sort()) {
  const cache = join(output, `${prefix}.json`)
  let data = existsSync(cache)
    ? JSON.parse(readFileSync(cache, 'utf8'))
    : { prefix, icons: {} }
  const missing = [...names].filter(
    name => !data.icons?.[name] && !data.aliases?.[name]
  )
  for (let start = 0; start < missing.length; start += 100) {
    const response = await fetch(
      `https://api.iconify.design/${prefix}.json?icons=${missing.slice(start, start + 100).join(',')}`
    )
    if (!response.ok)
      throw new Error(`Could not bundle ${prefix} icons: ${response.status}`)
    const next = await response.json()
    data = {
      ...data,
      ...next,
      icons: { ...data.icons, ...next.icons },
      aliases: { ...data.aliases, ...next.aliases }
    }
    delete data.not_found
  }
  writeFileSync(cache, JSON.stringify(data) + '\n')
  icons.push(prefix)
  notices.push({
    prefix,
    name: collections[prefix].name,
    author: collections[prefix].author,
    license: collections[prefix].license,
    source: `https://icon-sets.iconify.design/${prefix}/`
  })
}
writeFileSync(
  join(output, 'icon-notices.json'),
  JSON.stringify(notices, null, 2) + '\n'
)
writeFileSync(
  join(output, 'index.ts'),
  [
    '// Generated by pnpm exec node tools/desktop-assets.mjs; shared by every client.',
    "import type { IconifyJSON } from '@iconify/types'",
    ...icons.map(
      (prefix, index) => `import icons${index} from './${prefix}.json'`
    ),
    '',
    `const collections: IconifyJSON[] = [${icons.map((_, index) => `icons${index}`).join(', ')}]`,
    'export default collections',
    ''
  ].join('\n')
)
console.log(`Bundled ${icons.length} icon collections with attribution`)
